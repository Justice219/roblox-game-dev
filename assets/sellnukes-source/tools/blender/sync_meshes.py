#!/usr/bin/env python3
"""
sync_meshes.py — generate src/shared/Config/MeshAssets.luau from the Blender manifest + MeshId receipts.

Inputs:
    assets/blender/world/manifest.json   (generate_world.py)  piece sizes/offsets/colours/hashes
    assets/blender/world/mesh-ids.json   (upload_meshes.py)   MeshId per piece, bound to hashes
Output:
    src/shared/Config/MeshAssets.luau    MeshAssets[modelKey] = {pivot, triangles, order, pieces}

Hash matching (why a stale id can never ship):
    A piece gets its MeshId only if the receipt's contentHash equals the CURRENT manifest's
    contentHash for that model AND the piece hash matches. Rebuilding a model in Blender without
    re-uploading drops every id of that model to 0, so MeshLibrary uses the primitive fallback
    (correct size/colour) instead of an outdated mesh that no longer matches the manifest.

`order` lists piece names bottom-to-top (by the bottom of each piece's box, then name): the
build-in animation drops pieces in that order, LEGO style.

Concurrency: runs under the exclusive `.sn-manifest.lock` (shared with generate_world.py's
manifest merge), always regenerating from the full on-disk manifest + mesh-ids.json, so parallel
builders can each run it after their own uploads without dropping anyone's models.

Usage:
    python3 tools/blender/sync_meshes.py [--include-tests] [--check]
    --check: exit 1 if MeshAssets.luau is out of date (CI / scripts), write nothing.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

from snkit import cloud  # noqa: E402
from upload_meshes import content_hash  # noqa: E402

DIRECTORY = ROOT / "assets/blender/world"
OUTPUT = ROOT / "src/shared/Config/MeshAssets.luau"
MATERIALS = {"Studs", "StudsSmall", "StudsLarge", "Smooth", "Neon", "Glass"}

HEADER = """--!strict
--[[
	MeshAssets — GENERATED by tools/blender/sync_meshes.py. Do not edit by hand.

	One entry per Blender world model (tools/blender/models/*.py). Each piece is one single-colour
	MeshPart. `id` is the uploaded MeshId (0 = not uploaded yet, or the model changed since its
	upload: MeshLibrary then builds the primitive fallback from `size`/`offset`/`color`).
	`size`/`offset` are the piece's bounding box relative to the model pivot (studs, Roblox axes).
	`material` is a WorldMaterialConfig.Materials key ("Studs", "StudsSmall", "Neon", ...).
	`tinted` pieces take the caller's colour (MeshLibrary.spawn opts.tint / opts.colors).
	`order` lists pieces bottom-to-top for the LEGO build-in animation.

	Consumers: src/server/World/MeshLibrary.luau (spawn/preload), PlotBuilder/HubBuilder (B5),
	BuildIn (B6). Pipeline + budgets: docs/world-art.md.

	Example:
		local MeshAssets = require(ReplicatedStorage.Shared.Config.MeshAssets)
		print(MeshAssets.BuyPad.pieces.Top.size) --> Vector3
]]

export type Piece = {
	id: number,
	size: Vector3,
	offset: Vector3,
	color: Color3,
	material: string,
	tinted: boolean,
	transparency: number,
}

export type ModelAsset = {
	pivot: string,
	triangles: number,
	order: { string },
	pieces: { [string]: Piece },
}

local MeshAssets: { [string]: ModelAsset } = {}
"""


def num(value: float) -> str:
    """Compact, deterministic number literal (no exponent, trailing zeros trimmed)."""
    if not math.isfinite(value):
        raise SystemExit("non-finite number in manifest")
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def luau_string(value: str) -> str:
    """
    A double-quoted Luau string literal for `value`, always pure ASCII.

    Why not json.dumps: it writes non-ASCII as "\\u00b0", which Luau rejects ("malformed escape
    sequence") — one "°" in a pivot string broke every MeshAssets require in Studio (2026-10-31).
    Luau's form is \\u{XXXX}; control characters, quotes and backslashes are escaped too.
    Example: luau_string("rot 90°") -> '"rot 90\\u{b0}"'
    """
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F or code > 0x7E:
            out.append(f"\\u{{{code:x}}}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def comment_text(value: str) -> str:
    """`value` made safe for a single-line `--` comment (ASCII, no line breaks)."""
    return luau_string(value)[1:-1]


def render(manifest: dict, mesh_ids: dict, include_tests: bool) -> tuple[str, dict]:
    """Return (luau source, stats) for the given manifest + receipts."""
    lines = [HEADER]
    stats = {"models": 0, "pieces": 0, "uploaded": 0}
    for key in sorted(manifest):
        if key.startswith("StudTest") and not include_tests:
            continue
        entry = manifest[key]
        pieces = entry["pieces"]
        receipt = mesh_ids.get(key) or {}
        current = content_hash(pieces)
        fresh = receipt.get("contentHash") == current
        uploaded = (receipt.get("pieces") or {}) if fresh else {}
        order = sorted(pieces, key=lambda p: (round(p["offset"][1] - p["size"][1] / 2, 3), p["name"]))
        stats["models"] += 1
        lines.append(f"-- {comment_text(entry['pivot'])}")
        lines.append(f"MeshAssets.{key} = {{")
        lines.append(f"\tpivot = {luau_string(entry['pivot'])},")
        lines.append(f"\ttriangles = {int(entry['triangles'])},")
        lines.append("\torder = { " + ", ".join(luau_string(p["name"]) for p in order) + " },")
        lines.append("\tpieces = {")
        for piece in sorted(pieces, key=lambda p: p["name"]):
            name = piece["name"]
            if not cloud.NAME.fullmatch(name) or piece["material"] not in MATERIALS:
                raise SystemExit(f"{key}.{name}: invalid name or material {piece['material']}")
            row = uploaded.get(name) or {}
            mesh_id = row.get("meshId") if row.get("hash") == piece["hash"] else 0
            mesh_id = mesh_id if type(mesh_id) is int and mesh_id > 0 else 0
            stats["pieces"] += 1
            stats["uploaded"] += 1 if mesh_id else 0
            size = ", ".join(num(v) for v in piece["size"])
            offset = ", ".join(num(v) for v in piece["offset"])
            r, g, b = (int(c) for c in piece["color"])
            lines.append(f"\t\t{name} = {{")
            lines.append(f"\t\t\tid = {mesh_id},")
            lines.append(f"\t\t\tsize = Vector3.new({size}),")
            lines.append(f"\t\t\toffset = Vector3.new({offset}),")
            lines.append(f"\t\t\tcolor = Color3.fromRGB({r}, {g}, {b}),")
            lines.append(f"\t\t\tmaterial = {luau_string(piece['material'])},")
            lines.append(f"\t\t\ttinted = {'true' if piece['tinted'] else 'false'},")
            lines.append(f"\t\t\ttransparency = {num(float(piece['transparency']))},")
            lines.append("\t\t},")
        lines.append("\t},")
        lines.append("}")
        lines.append("")
    lines.append("return MeshAssets")
    return "\n".join(lines) + "\n", stats


def stylua(source: str) -> str:
    """Format through the repo's stylua (stylua.toml) so ./scripts/check.sh --check stays green."""
    binary = shutil.which("stylua") or str(Path.home() / ".aftman/bin/stylua")
    result = subprocess.run(
        [binary, "--stdin-filepath", str(OUTPUT), "-"],
        input=source.encode(),
        capture_output=True,
        cwd=ROOT,
        timeout=60,
        check=False,
    )
    if result.returncode != 0:
        raise SystemExit("[sync] stylua failed on the generated MeshAssets.luau")
    return result.stdout.decode()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    parser.add_argument("--include-tests", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # The whole read -> render -> write runs inside the manifest lock, so concurrent syncs are
    # serialised and each one renders from the newest manifest + mesh-ids (both written atomically),
    # i.e. the last sync to finish always reflects every builder's models.
    with cloud.exclusive(DIRECTORY, cloud.MANIFEST_LOCK):
        manifest = cloud.read_json(DIRECTORY / "manifest.json")
        mesh_ids = cloud.read_json(DIRECTORY / "mesh-ids.json", {})
        source, stats = render(manifest, mesh_ids, args.include_tests)
        source = stylua(source)
        # Guard: no JSON-style "\\uXXXX" escape may reach the module — Luau rejects it at compile
        # time and a single one breaks every MeshAssets require in Studio. (String literals are
        # always pure ASCII via luau_string; the header comment may hold UTF-8, which is valid.)
        if re.search(r"\\u[0-9a-fA-F]{4}", source):
            raise SystemExit("[sync] refusing to write MeshAssets.luau: a JSON-style \\u escape")
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if args.check:
            if current != source:
                print("[sync] MeshAssets.luau is out of date; run tools/blender/sync_meshes.py", file=sys.stderr)
                return 1
            print("[sync] MeshAssets.luau is up to date")
            return 0
        if current != source:
            # Same-directory temp file + rename: Rojo never syncs a half-written module.
            tmp = OUTPUT.with_name(f".{OUTPUT.name}.tmp")
            tmp.write_text(source, encoding="utf-8")
            tmp.replace(OUTPUT)
    print(
        f"[sync] {OUTPUT.relative_to(ROOT)}: {stats['models']} models, "
        f"{stats['uploaded']}/{stats['pieces']} pieces uploaded"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
